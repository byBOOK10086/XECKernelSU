#!/usr/bin/env python3
"""Stage the vendored SUSFS LKM sources under kernel/susfs/ for the merged LKM build.

Why this script exists
----------------------
`third_party/susfs4ksu-lkm` is a standalone out-of-tree module: its own Makefile turns
susfs_guard_lkm.ko out of its own directory. kbuild, however, only compiles sources that live
inside the directory handed to `M=`, so a build that puts SUSFS *into* kernelsu.ko has to move
the sources into kernel/. Copying them by hand would fork the vendored tree (and drag ~20k
lines of foreign code through clang-format and the quality budgets); this script regenerates
kernel/susfs/ from the pinned upstream sources at build time instead and does only the two
edits that the merge itself needs:

  1. RENAMES - the globals kernelsu.ko already defines get a `susfs_` prefix. Two independent
     copies of `ksu_lsm_hook`, `ksu_patch_text`, `find_kernel_symbol_exact` ... in one module
     are a link error, not a warning.
  2. BOILERPLATE - a module has exactly one module_init/module_exit, and it is ours. The
     upstream pair becomes ksu_susfs_lkm_init()/ksu_susfs_lkm_exit(), called from
     kernel/core/init.c under KSU_MERGE_SUSFS_LKM.

The directory is generated and gitignored; `make` in kernel/ is the only consumer and it only
looks at it when KSU_MERGE_SUSFS_LKM=1.

Usage:
    python3 scripts/prepare_susfs_lkm.py            # regenerate kernel/susfs/
    python3 scripts/prepare_susfs_lkm.py --check    # verify a staged tree is current
"""

from __future__ import annotations

import argparse
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "third_party" / "susfs4ksu-lkm" / "kernel"
DST = ROOT / "kernel" / "susfs"

# The probe/test tooling under kallrecon/ is not part of the module (see upstream's Makefile);
# only its lib/ is compiled.
SKIP_PREFIXES = ("kallrecon/src", "kallrecon/test")

# Longest first: `ksu_lsm_hook` must not eat `ksu_lsm_unhook`, and `ksu_patch_text` must not
# eat `ksu_patch_memory_init`.
RENAMES = [
    ("ksu_register_lsm_hook", "susfs_register_lsm_hook"),
    ("ksu_unregister_lsm_hook", "susfs_unregister_lsm_hook"),
    ("ksu_lsm_unhook", "susfs_lsm_unhook"),
    ("ksu_lsm_hook", "susfs_lsm_hook"),
    ("ksu_patch_memory_init", "susfs_patch_memory_init"),
    ("ksu_patch_text", "susfs_patch_text"),
    ("phys_from_virt", "susfs_phys_from_virt"),
    ("scan_call_to", "susfs_scan_call_to"),
    ("find_kernel_symbol_exact", "susfs_find_kernel_symbol_exact"),
    ("ksu_resolve_symbol_for_functable_hook", "susfs_resolve_symbol_for_functable_hook"),
    ("ksu_init_symbol_resolver", "susfs_init_symbol_resolver"),
]

BOILERPLATE = [
    # __init/__exit stay: the init path calls .init.text helpers (susfs_init_symbol_resolver
    # and friends), and modpost rejects a .text caller of .init.text with "Section mismatches
    # detected".  kernelsu_init()/kernelsu_exit() are __init/__exit themselves, so the calls
    # stay inside their own sections.
    ("static int __init susfs_init(void)", "int __init ksu_susfs_lkm_init(void)"),
    ("static void __exit susfs_exit(void)", "void __exit ksu_susfs_lkm_exit(void)"),
    ("module_init(susfs_init);", ""),
    ("module_exit(susfs_exit);", ""),
    ('MODULE_LICENSE("GPL");', ""),
]

# The merged module is loaded by ksuinit at boot, which passes no SUSFS parameters, so the
# upstream defaults are the only thing that can take effect.  Upstream defaults to the SukiSU
# domain ("u:r:ksu:s0"); this tree's superuser domain is stock "u:r:su:s0" - the same value ksud
# used to pass as avc_su_ctx=/su_ctx= when it loaded the module itself.
CONTEXTS = [
    (
        'static char avc_su_ctx[128] = "u:r:ksu:s0";',
        'static char avc_su_ctx[128] = "u:r:su:s0";',
    ),
    (
        'static char param_su_ctx[128] = "u:r:ksu:s0";',
        'static char param_su_ctx[128] = "u:r:su:s0";',
    ),
]

HEADER = (
    "/* GENERATED by scripts/prepare_susfs_lkm.py from third_party/susfs4ksu-lkm - do not edit.\n"
    " * Vendored SUSFS LKM sources, renamed where they collide with kernelsu.ko's own globals. */\n"
)


def sources() -> list[Path]:
    out = []
    for path in sorted(SRC.rglob("*")):
        if path.suffix not in (".c", ".h", ".S"):
            continue
        rel = path.relative_to(SRC).as_posix()
        if any(rel.startswith(p) for p in SKIP_PREFIXES):
            continue
        out.append(path)
    return out


def stage() -> int:
    if not SRC.is_dir():
        print(f"error: {SRC} is missing", file=sys.stderr)
        return 1
    files = sources()
    if not files:
        print(f"error: no sources under {SRC}", file=sys.stderr)
        return 1

    renames = 0
    replaced = 0
    contexts = 0
    staged = []
    for path in files:
        rel = path.relative_to(SRC)
        text = path.read_text(encoding="utf-8")
        for old, new in RENAMES:
            n = text.count(old)
            if n:
                text = text.replace(old, new)
                renames += n
        for old, new in BOILERPLATE:
            if old in text:
                text = text.replace(old, new)
                replaced += 1
        for old, new in CONTEXTS:
            if old in text:
                text = text.replace(old, new)
                contexts += 1
        if path.suffix in (".c", ".h"):
            text = HEADER + text
        staged.append((rel, text))

    if DST.exists():
        shutil.rmtree(DST)
    for rel, text in staged:
        target = DST / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8")
    (DST / ".gitignore").write_text("*\n", encoding="utf-8")

    # The three edits that must land, or the merge silently links the wrong thing.
    main = (DST / "susfs_main.c").read_text(encoding="utf-8")
    for needle in ("int __init ksu_susfs_lkm_init(void)", "void __exit ksu_susfs_lkm_exit(void)"):
        if needle not in main:
            print(f"error: {needle} missing from staged susfs_main.c", file=sys.stderr)
            return 1
    for needle in ("module_init(susfs_init)", "module_exit(susfs_exit)"):
        if needle in main:
            print(f"error: staged susfs_main.c still carries {needle}", file=sys.stderr)
            return 1
    if contexts != len(CONTEXTS):
        print(
            f"error: applied {contexts} of {len(CONTEXTS)} SELinux default fixes",
            file=sys.stderr,
        )
        return 1

    print(
        f"staged {len(staged)} files into {DST.relative_to(ROOT)} "
        f"({renames} symbol renames, {replaced} boilerplate lines, {contexts} context defaults)"
    )
    return 0


def check() -> int:
    if not DST.is_dir():
        print(f"error: {DST.relative_to(ROOT)} is not staged", file=sys.stderr)
        return 1
    missing = [
        p
        for p in sources()
        if not (DST / p.relative_to(SRC)).exists()
    ]
    if missing:
        print(f"error: staged tree is stale, missing {len(missing)} file(s)", file=sys.stderr)
        return 1
    print(f"{DST.relative_to(ROOT)} is up to date ({len(sources())} files)")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify the staged tree instead of writing it")
    args = parser.parse_args()
    return check() if args.check else stage()


if __name__ == "__main__":
    sys.exit(main())
